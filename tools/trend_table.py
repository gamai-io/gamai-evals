#!/usr/bin/env python3
"""Render the CUA trend table from results/cua-trend-2026-11-06.json.

Every rate in the output is computed from a `hits`/`n` pair in the JSON; nothing is
typed by hand. Intervals are Wilson score intervals at 95% (z = 1.959963984540054).

Usage:
  python3 tools/trend_table.py                      # print Markdown to stdout
  python3 tools/trend_table.py --out docs/TREND_TABLE.md
  python3 tools/trend_table.py --check              # fail if docs/TREND_TABLE.md is stale

Cells that are null, missing `hits`/`n`, or have n == 0 are reported as
"not measured" rather than as 0%.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

Z95 = 1.959963984540054
ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "results" / "cua-trend-2026-11-06.json"
DEFAULT_OUT = ROOT / "docs" / "TREND_TABLE.md"

NOT_MEASURED = "not measured"


def wilson_interval(hits: int, n: int, z: float = Z95) -> tuple[float, float]:
    """Wilson score interval for hits/n at the given z (95% by default)."""
    if n <= 0:
        raise ValueError("n must be > 0")
    if hits < 0 or hits > n:
        raise ValueError(f"hits must be in [0, n], got {hits}/{n}")
    p = hits / n
    denom = 1.0 + z * z / n
    centre = (p + z * z / (2.0 * n)) / denom
    half = (z / denom) * math.sqrt(p * (1.0 - p) / n + z * z / (4.0 * n * n))
    low, high = centre - half, centre + half
    # Exact bounds at the extremes; avoids 2.8e-17 style noise from cancellation.
    if hits == 0:
        low = 0.0
    if hits == n:
        high = 1.0
    return max(0.0, low), min(1.0, high)


def is_cell(value: object) -> bool:
    return isinstance(value, dict) and "hits" in value and "n" in value


def cell_row(adapter: str, mode: str, name: str, cell: object) -> str:
    """One table row. Null cells stay visible so a gap is not read as a zero."""
    if cell is None:
        return f"| {adapter} | {mode} | {name} | - | - | {NOT_MEASURED} | - | |"
    if not is_cell(cell):
        raise SystemExit(f"error: cell {adapter}/{name} is not a hits/n object: {cell!r}")

    hits, n = cell["hits"], cell["n"]
    if not isinstance(hits, int) or not isinstance(n, int):
        raise SystemExit(f"error: cell {adapter}/{name} has non-integer hits/n: {cell!r}")
    note = str(cell.get("note", "")).replace("|", "\\|")
    if n == 0:
        return f"| {adapter} | {mode} | {name} | {hits} | 0 | {NOT_MEASURED} | - | {note} |"

    low, high = wilson_interval(hits, n)
    rate = f"{100.0 * hits / n:.1f}%"
    ci = f"{100.0 * low:.1f}%\u2013{100.0 * high:.1f}%"
    return f"| {adapter} | {mode} | {name} | {hits} | {n} | {rate} | {ci} | {note} |"


def render(data: dict, source: Path) -> str:
    results = data.get("results")
    if not isinstance(results, list) or not results:
        raise SystemExit("error: JSON has no non-empty 'results' list")

    rel = source.relative_to(ROOT) if source.is_relative_to(ROOT) else source
    lines: list[str] = []
    lines.append("# CUA trend table (generated)")
    lines.append("")
    lines.append(f"Generated by `tools/trend_table.py` from `{rel}`. Do not edit by hand:")
    lines.append("regenerate with `python3 tools/trend_table.py --out docs/TREND_TABLE.md`.")
    lines.append("")
    lines.append(
        "Rates are `hits / n` as recorded in the JSON. Intervals are Wilson score intervals "
        "at 95% (z = 1.959963984540054). A null cell, or a cell with n = 0, is "
        "`not measured` \u2014 not a zero."
    )

    meta = []
    for key in ("date", "tolerance_px", "batch_size"):
        if key in data:
            meta.append(f"{key} = {data[key]}")
    if meta:
        lines.append("")
        lines.append("Source metadata: " + ", ".join(meta) + ".")
    lines.append("")
    lines.append(
        "The 600-item set is the union of the two 300-item sets "
        "(`tests/test_manifest_overlap.py`), so rows are not independent evidence; "
        "cite either the 600 or the two halves, not both as separate proof."
    )
    lines.append("")
    lines.append("| adapter | mode | measurement | hits | n | rate | Wilson 95% | note |")
    lines.append("|---|---|---|---:|---:|---:|---:|---|")

    for entry in results:
        if not isinstance(entry, dict) or "adapter" not in entry:
            raise SystemExit(f"error: result entry is not an adapter object: {entry!r}")
        adapter = str(entry["adapter"])
        mode = str(entry.get("mode", "-"))
        cells = [(k, v) for k, v in entry.items() if k not in ("adapter", "mode")]
        if not cells:
            raise SystemExit(f"error: adapter {adapter} has no measurement cells")
        for name, cell in cells:
            lines.append(cell_row(adapter, mode, name, cell))

    if data.get("invalid_baseline"):
        baseline = data["invalid_baseline"]
        model = baseline.get("model", "excluded baseline")
        reason = baseline.get("reason", "no reason recorded")
        status = baseline.get("status", "excluded")
        reported = baseline.get("reported")
        detail = f" Reported: {reported}." if reported else ""
        lines.append("")
        lines.append("## Excluded baseline")
        lines.append("")
        lines.append(f"- {model}: {status} \u2014 {reason}.{detail}")

    if data.get("measurement_correction"):
        correction = data["measurement_correction"]
        lines.append("")
        lines.append("## Measurement correction")
        lines.append("")
        for key, value in correction.items():
            lines.append(f"- {key}: {value}")

    if data.get("pixel_budget"):
        budget = data["pixel_budget"]
        lines.append("")
        lines.append("## Pixel budget")
        lines.append("")
        for regime, value in budget.items():
            if isinstance(value, dict):
                fields = ", ".join(f"{k}={v}" for k, v in value.items())
                lines.append(f"- {regime}: {fields}")
            else:
                lines.append(f"- {regime}: {value}")

    caveats = data.get("caveats") or []
    if caveats:
        lines.append("")
        lines.append("## Caveats")
        lines.append("")
        lines.extend(f"- {caveat}" for caveat in caveats)

    lines.append("")
    return "\n".join(lines)


def build(source: Path) -> str:
    try:
        data = json.loads(source.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise SystemExit(f"error: source JSON not found: {source}")
    except json.JSONDecodeError as exc:
        raise SystemExit(f"error: invalid JSON in {source}: {exc}")
    if not isinstance(data, dict):
        raise SystemExit(f"error: {source} must contain a JSON object")
    return render(data, source)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render the CUA trend table.")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="trend JSON")
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help="write here instead of stdout (default for --check: docs/TREND_TABLE.md)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the file at --out differs from freshly generated output",
    )
    args = parser.parse_args(argv)

    text = build(args.source)

    if args.check:
        target = args.out if args.out is not None else DEFAULT_OUT
        if not target.exists():
            print(f"error: {target} is missing; run: python3 tools/trend_table.py --out {target}", file=sys.stderr)
            return 1
        committed = target.read_text(encoding="utf-8")
        if committed != text:
            print(f"stale: {target} does not match tools/trend_table.py output", file=sys.stderr)
            expected = text.splitlines()
            actual = committed.splitlines()
            for i in range(max(len(expected), len(actual))):
                want = expected[i] if i < len(expected) else "<end of file>"
                have = actual[i] if i < len(actual) else "<end of file>"
                if want != have:
                    print(f"first difference at line {i + 1}:", file=sys.stderr)
                    print(f"  generated: {want}", file=sys.stderr)
                    print(f"  committed: {have}", file=sys.stderr)
                    break
            print(
                "regenerate with: python3 tools/trend_table.py --out " + str(target),
                file=sys.stderr,
            )
            return 1
        print(f"ok: {target} is current")
        return 0

    if args.out is None:
        sys.stdout.write(text)
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
